/** إيجاد أقرب مدينة / مركز مسجل في قاعدة البيانات */
export function findNearestIndexedPlace(lat: number, lng: number): IndexedPlace {
  let minDistance = Infinity;
  let nearest = ARAB_INDEXED_PLACES[0];

  for (const place of ARAB_INDEXED_PLACES) {
    const dLat = (place.lat - lat) * 111;
    const dLng = (place.lng - lng) * 111 * Math.cos((lat * Math.PI) / 180);
    const dist = Math.sqrt(dLat * dLat + dLng * dLng);

    if (dist < minDistance) {
      minDistance = dist;
      nearest = place;
    }
  }

  return nearest;
}
